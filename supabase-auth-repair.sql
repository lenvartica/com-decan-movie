-- DECAN MOVIE AUTH / ACCOUNT REPAIR
-- Run this once in Supabase SQL Editor.
-- It is designed to be safe when earlier account SQL was incomplete.
-- It creates the missing user_roles/is_admin pieces BEFORE policies reference them.

create extension if not exists pgcrypto;

-- 1) Core tables that the account page needs.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  avatar_url text,
  bio text,
  location text,
  favorite_genre text,
  coins integer not null default 0 check (coins >= 0),
  xp integer not null default 0 check (xp >= 0),
  streak_days integer not null default 0 check (streak_days >= 0),
  status text not null default 'active' check (status in ('active','suspended')),
  last_reward_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists bio text;
alter table public.profiles add column if not exists location text;
alter table public.profiles add column if not exists favorite_genre text;
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists coins integer not null default 0;
alter table public.profiles add column if not exists xp integer not null default 0;
alter table public.profiles add column if not exists streak_days integer not null default 0;
alter table public.profiles add column if not exists status text not null default 'active';
alter table public.profiles add column if not exists last_reward_date date;
alter table public.profiles add column if not exists created_at timestamptz not null default now();
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.user_library (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  library_type text not null check (library_type in ('watchlist','favorites','history','customlist','continue','ratings')),
  movie_id bigint not null,
  media_type text,
  item jsonb not null,
  updated_at timestamptz not null default now(),
  unique(user_id, library_type, movie_id)
);

create table if not exists public.daily_claims (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  claim_date date not null default current_date,
  amount integer not null,
  created_at timestamptz not null default now(),
  unique(user_id, claim_date)
);

create table if not exists public.coin_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount integer not null,
  balance_after integer,
  type text not null,
  description text,
  reference_id text,
  created_at timestamptz not null default now()
);

-- 2) Admin helper MUST exist before any policy calls it.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

-- 3) Automatically create a profile + normal user role after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id, username, display_name)
  values (
    new.id,
    nullif(new.raw_user_meta_data->>'username',''),
    coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(coalesce(new.email,''),'@',1))
  )
  on conflict (id) do nothing;

  insert into public.user_roles(user_id, role)
  values(new.id,'user')
  on conflict(user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Repair existing accounts that were created before the trigger existed.
insert into public.profiles(id, username, display_name)
select u.id,
       nullif(u.raw_user_meta_data->>'username',''),
       coalesce(nullif(u.raw_user_meta_data->>'display_name',''), split_part(coalesce(u.email,''),'@',1))
from auth.users u
on conflict(id) do nothing;

insert into public.user_roles(user_id, role)
select u.id,'user' from auth.users u
on conflict(user_id) do nothing;

