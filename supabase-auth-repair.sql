-- 6) Daily coins. One claim per account per database date.
create or replace function public.claim_daily_reward()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  today date := current_date;
  old_balance integer := 0;
  old_streak integer := 0;
  new_balance integer := 0;
  new_streak integer := 1;
  reward integer := 10;
begin
  if uid is null then raise exception 'Authentication required'; end if;

  if exists(select 1 from public.daily_claims where user_id=uid and claim_date=today) then
    select coalesce(coins,0),coalesce(streak_days,0) into old_balance,old_streak from public.profiles where id=uid;
    return jsonb_build_object('claimed',false,'amount',0,'coins',old_balance,'streak',old_streak);
  end if;

  select coalesce(coins,0),coalesce(streak_days,0) into old_balance,old_streak
  from public.profiles where id=uid for update;

  if exists(select 1 from public.daily_claims where user_id=uid and claim_date=today-1) then
    new_streak := greatest(1,old_streak+1);
  else
    new_streak := 1;
  end if;

  reward := 10 + least(new_streak,7)*2;
  new_balance := old_balance + reward;

  update public.profiles set coins=new_balance,streak_days=new_streak,last_reward_date=today,updated_at=now() where id=uid;
  insert into public.daily_claims(user_id,claim_date,amount) values(uid,today,reward);
  insert into public.coin_transactions(user_id,amount,balance_after,type,description) values(uid,reward,new_balance,'daily_reward','Daily login reward');

  return jsonb_build_object('claimed',true,'amount',reward,'coins',new_balance,'streak',new_streak);
end;
$$;

grant execute on function public.claim_daily_reward() to authenticated;
